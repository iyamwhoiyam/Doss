/**
 * Collection definitions for the Enova Ops file-system database.
 *
 * Each entry declares the fields the engine validates, the secondary indexes it
 * maintains, and which fields must be unique. `search` lists the fields the
 * global search and list filters scan. `audit: false` opts a high-churn
 * collection out of the append-only audit trail.
 */

