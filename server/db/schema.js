const str = (label, extra = {}) => ({ type: 'string', label, ...extra });
const num = (label, extra = {}) => ({ type: 'number', label, ...extra });
const bool = (label, def = false) => ({ type: 'boolean', label, default: def });
const arr = (label) => ({ type: 'array', label, default: [] });
const obj = (label) => ({ type: 'object', label, default: {} });
const date = (label) => ({ type: 'date', label, default: null });
const oneOf = (label, list, def) => ({ type: 'string', label, enum: enumValues(list), default: def });

const stageValues = [...enumValues(PROJECT_STAGES), ...enumValues(PROJECT_TERMINAL)];
const woStageValues = [...enumValues(WORK_ORDER_STAGES), ...enumValues(WORK_ORDER_TERMINAL)];

